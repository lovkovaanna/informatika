# TODO  Напишите функцию count_letters
def count_letters(text):
    letter_count = {} #Создаём пустой словарь для подсчёта букв
    text_lower = text.lower() #Приводим весь текст к нижнему регистру
    for char in text_lower: #Перебираем каждый символ в тексте
        if char.isalpha(): #Проверяем, является ли символ буквой
            letter_count[char] = letter_count.get(char, 0) + 1 #Увеличиваем счётчик для этой буквы
    return letter_count  #Возвращаем словарь с результатами

# TODO Напишите функцию calculate_frequency
def calculate_frequency(letter_count): #Вычисляет частоту каждой буквы на основе словаря с количествами.
    total_letters = sum(letter_count.values()) #Вычисляем общее количество всех букв
    frequency = {} #Создаём пустой словарь для частот
    for letter, count in letter_count.items(): #Перебираем все пары (буква, количество) из словаря
        frequency[letter] = round(count / total_letters, 2) #Вычисляем частоту = количество / общее количество
    return frequency #Возвращаем словарь с частотами


